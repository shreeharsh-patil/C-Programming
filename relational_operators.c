#include <stdio.h>

int main()
{
    int x = 60, y = 30;
    printf("Relational Operators testing between %d and %d:\n", x, y);
    printf("60 == 30 -> %d\n", x == y);
    printf("60 != 30 -> %d\n", x != y);
    printf("60 >= 30 -> %d\n", x >= y);
    printf("60 <= 30 -> %d\n", x <= y);
    printf("60 < 30  -> %d\n", x < y);
    printf("60 > 30  -> %d\n", x > y);
    return 0;
}
